import { chromium } from 'playwright'
const exe = '/root/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome'
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = await ctx.newPage()
page.on('pageerror', (e) => console.log('PAGEERROR', e.message))
page.on('console', (m) => console.log('CONSOLE', m.type(), m.text().slice(0,200)))
page.on('request', (r) => { if (r.url().includes('/api/')) console.log('REQ', r.method(), r.url().split('/api/')[1]) })
page.on('response', (r) => { if (r.url().includes('/cutting')) console.log('CUT RESP', r.status()) })
await page.goto(`${process.env.BASE_URL || 'http://127.0.0.1:4173'}/?perf=1`, { waitUntil: 'networkidle', timeout: 40000 })
const demo = page.getByText('Посмотреть демо', { exact: false })
if (await demo.count()) await demo.first().click()
await page.waitForTimeout(6000)
const skip = page.locator('.tour__skip')
if (await skip.count()) await skip.first().click().catch(() => {})
await page.locator('[data-tour="more"]').click()
await page.getByRole('button', { name: 'Быстрый старт' }).click()
await page.waitForTimeout(400)
await page.locator('.quick__name input').fill('Кухня раскрой')
await page.getByRole('button', { name: 'Создать проект' }).click()
await page.waitForTimeout(9000)
console.log('asset', await page.evaluate(() => [...document.scripts].map(s=>s.src).filter(Boolean).join(',')))
const res = await page.evaluate(async () => {
  const pid = window.__furnitureDbg.state.projectId
  const r = await fetch(`/api/projects/${pid}/cutting`, { method: 'POST' })
  const j = await r.json().catch(() => ({}))
  return { pid, status: r.status, totals: j.totals, err: j.detail || j.errors }
})
console.log(JSON.stringify(res))
await page.locator('[data-tour="more"]').click()
await page.getByRole('button', { name: 'Готовый проект' }).click()
await page.waitForTimeout(12000)
console.log((await page.locator('.result__stats').innerText()).replace(/\n/g, ' | '))
console.log((await page.locator('.result__note').first().innerText()).slice(0, 200))
await browser.close()
